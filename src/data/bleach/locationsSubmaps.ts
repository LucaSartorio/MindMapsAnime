/**
 * Luoghi delle sotto-mappe di Bleach: Seireitei, Hueco Mundo (Las Noches) e
 * Reiōkyū.
 *
 * Seireitei (`bl-map-seireitei`, 1600 × 1000): mura circolari centrate in
 * (800, 510) con raggio 430. La Prima Divisione sta al centro; le altre dodici
 * caserme sono disposte su un anello di raggio 250 (`division_positions()` in
 * `scripts/bleach-maps.py`). L'opera non dà una pianta della città: l'ordine
 * delle caserme e la posizione di Sōkyoku, Senzaikyū, Central 46, villa Kuchiki
 * e Accademia sono schematici, mentre i luoghi in sé sono canonici.
 *
 * Hueco Mundo (`bl-map-hueco-mundo`, 1600 × 1000): la cupola di Las Noches è
 * l'ellisse centrata in (900, 575); fuori, il deserto e la Garganta a
 * nord-ovest. Reiōkyū (`bl-map-reiokyu`, 1400 × 1000): il bozzolo del Re al
 * centro in alto, i palazzi della Divisione Zero sui dischi sospesi.
 */

/** Caserma di una Divisione: descrizione + coordinate dall'anello del Seireitei. */
const division = (
  n: number,
  x: number,
  y: number,
  data: Pick<Location, 'shortDescription' | 'longDescription' | 'characterIds' | 'eventIds' | 'arcIds'> & {
    importance?: Location['importance'];
    tags?: string[];
  },
): Location => {
  const ord = ['', '1st', '2nd', '3rd', '4th', '5th', '6th', '7th', '8th', '9th', '10th', '11th', '12th', '13th'][n];
  return loc({
    id: `loc-bl-division-${n}`,
    mapLevelId: 'bl-map-seireitei',
    name: `${ord} Division barracks`,
    localizedName: { it: `Caserma ${n}ª Divisione`, en: `${ord} Division barracks`, ja: `${n}番隊隊舎` },
    type: 'landmark',
    x,
    y,
    nationId: 'nation-bl-soul-society',
    clanIds: [`faction-bl-division-${n}`],
    importance: data.importance ?? 'secondary',
    shortDescription: data.shortDescription,
    longDescription: data.longDescription,
    characterIds: data.characterIds,
    eventIds: data.eventIds,
    arcIds: data.arcIds,
    tags: ['gotei-13', 'divisione', ...(data.tags ?? [])],
  });
};

