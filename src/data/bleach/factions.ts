import type { Faction } from '@/types';

const fac = (f: Omit<Faction, 'worldId'>): Faction => ({
  worldId: 'world-bleach',
  canonStatus: 'canon',
  referenceStatus: 'verified',
  ...f,
});

/**
 * Fazioni di Bleach (facet «Divisioni & Fazioni»). Il campo `type` distingue:
 *  - `division`     → le tredici Divisioni del Gotei 13 (una scheda ciascuna);
 *  - `organization` → Gotei 13, Central 46, Divisione Kidō, Onmitsukidō,
 *                     Divisione Zero, Xcution, Negozio Urahara;
 *  - `clan`         → le casate nobili (Kuchiki, Shihōin, Shiba) e i Quincy;
 *  - `army` / `group` → l'esercito di Aizen e gli Espada, il Wandenreich e i
 *                     suoi corpi, i Visored, gli amici di Ichigo.
 */
const division = (
  n: number,
  data: Omit<Faction, 'worldId' | 'id' | 'type' | 'name' | 'localizedName' | 'japaneseName' | 'nationId' | 'villageLocationId'> & {
    insignia: string;
  },
): Faction => {
  const ord = ['', '1st', '2nd', '3rd', '4th', '5th', '6th', '7th', '8th', '9th', '10th', '11th', '12th', '13th'][n];
  const ita = ['', 'Prima', 'Seconda', 'Terza', 'Quarta', 'Quinta', 'Sesta', 'Settima', 'Ottava', 'Nona', 'Decima', 'Undicesima', 'Dodicesima', 'Tredicesima'][n];
  const { insignia, ...rest } = data;
  return fac({
    id: `faction-bl-division-${n}`,
    type: 'division',
    name: `${ord} Division`,
    localizedName: { it: `${ita} Divisione`, en: `${ord} Division`, ja: `${n}番隊` },
    japaneseName: `${n}番隊`,
    nationId: 'nation-bl-soul-society',
    villageLocationId: `loc-bl-division-${n}`,
    ...rest,
    locationIds: [`loc-bl-division-${n}`, ...(rest.locationIds ?? [])],
    tags: ['gotei-13', 'divisione', `insegna-${insignia}`, ...(rest.tags ?? [])],
  });
};

