import type { Location } from '@/types';

/** Default comuni ai luoghi di Jujutsu Kaisen (canon e verificati salvo override). */
export const loc = (l: Omit<Location, 'worldId'>): Location => ({
  worldId: 'world-jujutsukaisen',
  canonStatus: 'canon',
  referenceStatus: 'verified',
  ...l,
});

/** Pin di ritorno al livello superiore (esclusi dall'indice SEO). */
const back = (b: { id: string; x: number; y: number; mapLevelId: string; to: string; it: string; en: string; nationId: string }): Location =>
  loc({
    id: b.id,
    mapLevelId: b.mapLevelId,
    name: b.en,
    localizedName: { it: b.it, en: b.en },
    type: 'region',
    x: b.x,
    y: b.y,
    subMapLevelId: b.to,
    shortDescription: { it: 'Doppio clic per risalire alla mappa superiore.', en: 'Double-click to go back up to the parent map.' },
    nationId: b.nationId,
    importance: 'minor',
    tags: ['navigazione'],
  });

/** Una delle colonie del Culling Game in cui la serie non ambienta scontri. */
const colony = (c: { id: string; x: number; y: number; name: string; nationId: string; it: string; en: string }): Location =>
  loc({
    id: c.id,
    mapLevelId: 'jjk-map-japan',
    name: `${c.name} Colony`,
    localizedName: { it: `Colonia di ${c.name}`, en: `${c.name} Colony` },
    type: 'battlefield',
    x: c.x,
    y: c.y,
    shortDescription: {
      it: `Una delle dieci barriere del Culling Game, disposte in fila lungo il Giappone: ${c.it}. La serie non vi ambienta scontri: la posizione esatta della cupola è indicativa.`,
      en: `One of the ten Culling Game barriers, lined up along Japan: ${c.en}. The series sets no battles there: the exact position of the dome is indicative.`,
    },
    nationId: c.nationId,
    importance: 'minor',
    referenceStatus: 'needs_verification',
    tags: ['culling-game', 'colonia'],
  });

